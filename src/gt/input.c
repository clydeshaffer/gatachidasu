#define INTDATA ((int*) rawData)


#pragma optimize (push, off)
void update_inputs(){
    char inputsA, inputsB;
    inputsA = *gamepad_2;
    inputsA = *gamepad_1;
    inputsB = *gamepad_1;

    player1_old_buttons = player1_buttons;
    player1_buttons = ~((((int) inputsB) << 8) | inputsA);
    player1_buttons &= INPUT_MASK_ALL_KEYS;
    

    inputsA = *gamepad_2;
    inputsB = *gamepad_2;
    player2_old_buttons = player2_buttons;
    player2_buttons = ~((((int) inputsB) << 8) | inputsA);
    player2_buttons &= INPUT_MASK_ALL_KEYS;
    
    if(player1_buttons) {
        enable_playback = 0;
    }

    if(enable_playback) {
        if(record_index < (sizeof(rawData) / sizeof(int))) {
            if(record_frame_count >= INTDATA[record_index]) {
                ++record_index;
                replay_button_state ^= INTDATA[record_index++];
                record_frame_count = 0;
            }
        } else {
            enable_playback = 0;
            replay_button_state = 0;
        }
        player1_buttons = replay_button_state;
        ++record_frame_count;
    }

    player1_new_buttons = player1_buttons & ~player1_old_buttons;
    player2_new_buttons = player2_buttons & ~player2_old_buttons;

    if(enable_record) {
        ++record_frame_count;
        if(record_index < INPUT_RECORD_INT_COUNT) {
            if(player1_buttons != player1_old_buttons) {
                demo_replay[record_index++] = record_frame_count;
                demo_replay[record_index++] = player1_buttons ^ player1_old_buttons;
                record_frame_count = 0;
            }
        } else {
            enable_record = 0;
        }
    }
}
#pragma optimize (pop)

void start_playback() {
    enable_playback = 1;
    record_frame_count = 0;
    record_index = 0;
    replay_button_state = 0;
}